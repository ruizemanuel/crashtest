#!/usr/bin/env node
// SPIKE (S2): in-place overlay. node apply-overlay.mjs <appDir>
// Renames agent/agent.ts and agent/tools/<t>.ts to *.ctorig.spec.ts (eve discovery ignores *.spec.*)
// and writes generated shims that import the originals. Idempotent.
import { existsSync, readdirSync, renameSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const app = resolve(process.argv[2] ?? ".");
const agentDir = join(app, "agent");
const toolsDir = join(agentDir, "tools");
const ORIG = ".ctorig.spec";
const HEADER = "// GENERATED by crashtest overlay (spike S2). Do not edit.\n";

function moveOriginal(dir, name) {
  const original = join(dir, `${name}.ts`);
  const moved = join(dir, `${name}${ORIG}.ts`);
  if (!existsSync(moved)) renameSync(original, moved);
}

// Agent shim: keep everything the user defined, swap only the model for a scripted mock.
moveOriginal(agentDir, "agent");
writeFileSync(join(agentDir, "agent.ts"), `${HEADER}import { defineAgent } from "eve";
import { mockModel } from "eve/evals";
import original from "./agent${ORIG}";

export default defineAgent({
  ...original,
  model: mockModel({
    modelId: "crashtest-script",
    provider: "crashtest",
    respond: ({ toolResults }) =>
      toolResults.length === 0
        ? { toolCalls: [{ name: "notify", input: { to: "alice", text: "Hi Alice" } }] }
        : \`Done: \${JSON.stringify(toolResults)}\`,
  }),
});
`);

// Tool shims: pure re-export of the original definition (crashes come from the preload).
const tools = readdirSync(toolsDir)
  .filter((f) => f.endsWith(".ts") && !/\.(spec|test)\./.test(f))
  .map((f) => f.slice(0, -3));
for (const name of tools) {
  moveOriginal(toolsDir, name);
  writeFileSync(join(toolsDir, `${name}.ts`), `${HEADER}import { defineTool } from "eve/tools";
import original from "./${name}${ORIG}";

export default defineTool({ ...original });
`);
}
console.log(JSON.stringify({ app, agent: "shimmed", tools }));
