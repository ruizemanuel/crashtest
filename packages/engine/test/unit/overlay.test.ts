import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { EngineError } from "../../src/errors.ts";
import { applyOverlay } from "../../src/overlay.ts";
import { templatePath } from "../../src/paths.ts";

const AGENT_SHIM = `// GENERATED by crashtest. Do not edit.
import { defineAgent } from "eve";
import { mockModel } from "eve/evals";
import { createResponder } from "./crashtest_responder.ctgen.spec";
import original from "./agent.ctorig.spec";

export default defineAgent({
  ...original,
  model: mockModel({ modelId: "crashtest-script", provider: "crashtest", respond: createResponder() }),
});
`;

const AGENT_SHIM_WITHOUT_ORIGINAL = `// GENERATED by crashtest. Do not edit.
import { defineAgent } from "eve";
import { mockModel } from "eve/evals";
import { createResponder } from "./crashtest_responder.ctgen.spec";

export default defineAgent({
  model: mockModel({ modelId: "crashtest-script", provider: "crashtest", respond: createResponder() }),
});
`;

const CHANNEL_SHIM = `// GENERATED by crashtest. Do not edit.
import { eveChannel } from "eve/channels/eve";
import { localDev } from "eve/channels/auth";

export default eveChannel({ auth: [localDev()] });
`;

const ORIGINAL_AGENT = `import { defineAgent } from "eve";\nexport default defineAgent({ model: "anthropic/claude-haiku-5.5" });\n`;
const ORIGINAL_CHANNEL = `import { eveChannel } from "eve/channels/eve";\nexport default eveChannel({ auth: [] });\n`;
const TOOL = `export default { description: "stub tool" };\n`;

function put(root: string, rel: string, content: string): void {
  const file = join(root, ...rel.split("/"));
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

function read(root: string, rel: string): string {
  return readFileSync(join(root, ...rel.split("/")), "utf8");
}

function files(root: string, rel = ""): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(join(root, rel), { withFileTypes: true })) {
    const child = rel === "" ? entry.name : `${rel}/${entry.name}`;
    if (entry.isDirectory()) out.push(...files(root, child));
    else out.push(child);
  }
  return out.sort();
}

/** Paths, contents and modification times: a second overlay must not touch anything. */
function snapshot(root: string): string {
  const hash = createHash("sha256");
  for (const rel of files(root)) {
    hash.update(`${rel}\0${read(root, rel)}\0${statSync(join(root, ...rel.split("/"))).mtimeMs}\0`);
  }
  return hash.digest("hex");
}

function withTemp(fn: (labDir: string) => void): void {
  const labDir = mkdtempSync(join(tmpdir(), "ct-overlay-"));
  try {
    fn(labDir);
  } finally {
    rmSync(labDir, { recursive: true, force: true, maxRetries: 3 });
  }
}

test("overlay wraps the agent and the eve channel, adds the responder and the hook, and leaves tools alone", () => {
  withTemp((labDir) => {
    put(labDir, "agent/agent.ts", ORIGINAL_AGENT);
    put(labDir, "agent/channels/eve.ts", ORIGINAL_CHANNEL);
    put(labDir, "agent/tools/notify.ts", TOOL);
    put(labDir, "agent/instructions.md", "Be brief.\n");

    assert.deepEqual(applyOverlay(labDir), { agentShimmed: true, channelShimmed: true });

    assert.equal(read(labDir, "agent/agent.ctorig.spec.ts"), ORIGINAL_AGENT);
    assert.equal(read(labDir, "agent/agent.ts"), AGENT_SHIM);
    assert.equal(read(labDir, "agent/channels/eve.ctorig.spec.ts"), ORIGINAL_CHANNEL);
    assert.equal(read(labDir, "agent/channels/eve.ts"), CHANNEL_SHIM);
    assert.equal(read(labDir, "agent/crashtest_responder.ctgen.spec.ts"), readFileSync(templatePath("responder.ts"), "utf8"));
    assert.equal(read(labDir, "agent/hooks/crashtest_probe.ts"), readFileSync(templatePath("probe-hook.ts"), "utf8"));
    assert.equal(read(labDir, "agent/tools/notify.ts"), TOOL);
    assert.equal(read(labDir, "agent/instructions.md"), "Be brief.\n");
    assert.deepEqual(files(labDir), [
      "agent/agent.ctorig.spec.ts",
      "agent/agent.ts",
      "agent/channels/eve.ctorig.spec.ts",
      "agent/channels/eve.ts",
      "agent/crashtest_responder.ctgen.spec.ts",
      "agent/hooks/crashtest_probe.ts",
      "agent/instructions.md",
      "agent/tools/notify.ts",
    ]);
  });
});

test("overlay is idempotent: a second call changes nothing and keeps the originals", () => {
  withTemp((labDir) => {
    put(labDir, "agent/agent.ts", ORIGINAL_AGENT);
    put(labDir, "agent/channels/eve.ts", ORIGINAL_CHANNEL);
    const first = applyOverlay(labDir);
    const before = snapshot(labDir);

    assert.deepEqual(applyOverlay(labDir), first);
    assert.equal(snapshot(labDir), before);
    assert.equal(read(labDir, "agent/agent.ctorig.spec.ts"), ORIGINAL_AGENT);
    assert.equal(read(labDir, "agent/channels/eve.ctorig.spec.ts"), ORIGINAL_CHANNEL);
  });
});

test("overlay without an agent.ts writes a shim with no original import and no spread", () => {
  withTemp((labDir) => {
    put(labDir, "agent/instructions.md", "Be brief.\n");

    assert.deepEqual(applyOverlay(labDir), { agentShimmed: false, channelShimmed: false });
    assert.equal(read(labDir, "agent/agent.ts"), AGENT_SHIM_WITHOUT_ORIGINAL);
    assert.equal(existsSync(join(labDir, "agent", "agent.ctorig.spec.ts")), false);
    assert.equal(existsSync(join(labDir, "agent", "channels")), false, "no eve channel in the app: none is created");
    assert.ok(existsSync(join(labDir, "agent", "crashtest_responder.ctgen.spec.ts")));
    assert.ok(existsSync(join(labDir, "agent", "hooks", "crashtest_probe.ts")));
  });
});

test("overlay without an agent.ts is idempotent and never mistakes its own shim for the user's agent", () => {
  withTemp((labDir) => {
    put(labDir, "agent/instructions.md", "Be brief.\n");
    applyOverlay(labDir);
    const before = snapshot(labDir);

    assert.deepEqual(applyOverlay(labDir), { agentShimmed: false, channelShimmed: false });
    assert.equal(snapshot(labDir), before);
    assert.equal(existsSync(join(labDir, "agent", "agent.ctorig.spec.ts")), false);
  });
});

test("overlay repairs a shim or a copied file that was edited by hand", () => {
  withTemp((labDir) => {
    put(labDir, "agent/agent.ts", ORIGINAL_AGENT);
    applyOverlay(labDir);
    put(labDir, "agent/agent.ts", `${AGENT_SHIM}// tampered\n`);
    put(labDir, "agent/hooks/crashtest_probe.ts", "// tampered\n");

    applyOverlay(labDir);

    assert.equal(read(labDir, "agent/agent.ts"), AGENT_SHIM);
    assert.equal(read(labDir, "agent/hooks/crashtest_probe.ts"), readFileSync(templatePath("probe-hook.ts"), "utf8"));
    assert.equal(read(labDir, "agent/agent.ctorig.spec.ts"), ORIGINAL_AGENT);
  });
});

const STALE = "// stale\n";

test("overlay refuses a user's agent.ts that sits next to a stale original, instead of picking one", () => {
  withTemp((labDir) => {
    put(labDir, "agent/agent.ts", ORIGINAL_AGENT);
    put(labDir, "agent/agent.ctorig.spec.ts", STALE);

    assert.throws(() => applyOverlay(labDir), (error: unknown) => error instanceof EngineError && /both exist/.test(error.message));
    assert.equal(read(labDir, "agent/agent.ts"), ORIGINAL_AGENT);
    assert.equal(read(labDir, "agent/agent.ctorig.spec.ts"), STALE);
  });
});
