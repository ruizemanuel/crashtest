// The overlay turns a lab copy into something crashtest can drive: the agent's model becomes a scripted
// mock and a crash hook is added. The user's own files are renamed to `*.ctorig.spec.ts` (eve ignores
// `*.spec.*` when it discovers files, but they can still be imported) and generated shims take their place.
// Tool files are never touched: a crash comes from the preload and the hook, not from wrapping a tool.
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { EngineError } from "./errors.ts";
import { templatePath } from "./paths.ts";

const GENERATED_HEADER = "// GENERATED by crashtest. Do not edit.\n";

/** The extensions eve loads an authored module with (the same in eve 1.2.0 and 1.5.0). */
const CHANNEL_EXTENSIONS = [".ts", ".mts", ".cts", ".js", ".mjs", ".cjs"] as const;

const AGENT_SHIM_HEAD = `${GENERATED_HEADER}import { defineAgent } from "eve";
import { mockModel } from "eve/evals";
import { createResponder } from "./crashtest_responder.ctgen.spec";
`;

const AGENT_SHIM_MODEL = `  model: mockModel({ modelId: "crashtest-script", provider: "crashtest", respond: createResponder() }),
});
`;

/** Wraps the user's agent: everything they defined is kept, only the model is replaced. */
const AGENT_SHIM = `${AGENT_SHIM_HEAD}import original from "./agent.ctorig.spec";

export default defineAgent({
  ...original,
${AGENT_SHIM_MODEL}`;

/** For an app without an `agent/agent.ts`. */
const AGENT_SHIM_WITHOUT_ORIGINAL = `${AGENT_SHIM_HEAD}
export default defineAgent({
${AGENT_SHIM_MODEL}`;

/**
 * Lets the driver call the HTTP channel without credentials and gives the session the identity a tool checks
 * (`CT_SESSION_AUTH`, set per cell from `crashtest.config.json`). An original channel stays next to it.
 */
const CHANNEL_SHIM = `${GENERATED_HEADER}import { eveChannel } from "eve/channels/eve";
import { localDev } from "eve/channels/auth";

const local = localDev();

/** Local callers only; a session gets the identity crashtest.config.json sets for the tool, else eve's local caller. */
export default eveChannel({
  auth: [
    async (request) => {
      const caller = await local(request);
      if (!caller) return null;
      const configured = process.env.CT_SESSION_AUTH;
      return configured ? JSON.parse(configured) : caller;
    },
  ],
});
`;

/**
 * Overlays the lab in place. Safe to call again: originals are renamed only once, and a file that is
 * already the right content is left untouched (so its modification time stays).
 * `agentShimmed` and `channelShimmed` say whether the lab has an original agent / eve channel that a shim
 * now wraps or replaces. An app without an `agent/agent.ts` still gets the agent shim, just without that wrapping,
 * and an app without an `agent/channels/eve.<ext>` still gets the lab channel.
 */
export function applyOverlay(labDir: string): { agentShimmed: boolean; channelShimmed: boolean } {
  const agentDir = join(labDir, "agent");

  const agentShimmed = moveOriginal(join(agentDir, "agent.ts"), join(agentDir, "agent.ctorig.spec.ts"));
  writeIfChanged(join(agentDir, "agent.ts"), agentShimmed ? AGENT_SHIM : AGENT_SHIM_WITHOUT_ORIGINAL);

  copyIfChanged(templatePath("responder.ts"), join(agentDir, "crashtest_responder.ctgen.spec.ts"));
  copyIfChanged(templatePath("probe-hook.ts"), join(agentDir, "hooks", "crashtest_probe.ts"));

  // eve discovers an authored module with any of these extensions, so every `eve<ext>` has to give way to the lab
  // channel, or eve would see two channels with the same stem.
  const channelsDir = join(agentDir, "channels");
  const moved = CHANNEL_EXTENSIONS.map((ext) => moveOriginal(join(channelsDir, `eve${ext}`), join(channelsDir, `eve.ctorig.spec${ext}`)));
  const channelShimmed = moved.some(Boolean);
  writeIfChanged(join(channelsDir, "eve.ts"), CHANNEL_SHIM);

  return { agentShimmed, channelShimmed };
}

/**
 * Renames the user's file to `moved` unless that already happened, or unless `file` is one of our own
 * shims (a lab that was overlaid before). True when the user's original is in `moved` afterwards.
 * A user's file next to a stale `moved` is refused: either one could be the agent under test.
 */
function moveOriginal(file: string, moved: string): boolean {
  if (!existsSync(file) || isGenerated(file)) return existsSync(moved);
  if (existsSync(moved)) {
    throw new EngineError(`${file} and ${moved} both exist and the first is not a crashtest shim: remove the stale ${moved} so the overlay knows which one is yours`);
  }
  renameSync(file, moved);
  return true;
}

function isGenerated(file: string): boolean {
  return readFileSync(file, "utf8").startsWith(GENERATED_HEADER.trimEnd());
}

function writeIfChanged(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

function copyIfChanged(from: string, to: string): void {
  if (existsSync(to) && readFileSync(to).equals(readFileSync(from))) return;
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
}
